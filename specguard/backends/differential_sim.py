def _extract_json(stdout: str) -> Optional[Dict[str, Any]]:
    """Extract JSON payload from forge output, skipping any warnings."""
    if not stdout:
        return None
    start = stdout.find("{")
    end = stdout.rfind("}")
    if start != -1 and end != -1 and end > start:
        try:
            return json.loads(stdout[start : end + 1])
        except Exception:
            pass
    return None


def _evaluate_json_results(
    json_data: Dict[str, Any],
    returncode: int,
    harness_code: str,
    property_id: str,
    raw_log_path: str,
    backend_name: str = "DifferentialSim",
) -> ValidationResult:
    """
    Evaluate parsed forge --json output and return a structured ValidationResult.

    Rule B: decisions are made purely on structured JSON test data — no substring
    inspection of console output.
    """
    total_tests = 0
    failed_tests: List[Tuple[str, Dict[str, Any]]] = []
    setup_errors: List[str] = []

    for _contract_key, contract_data in json_data.items():
        if not isinstance(contract_data, dict):
            continue
        if contract_data.get("error"):
            setup_errors.append(str(contract_data["error"]))

        test_results = contract_data.get("test_results", {})
        for test_name, test_data in test_results.items():
            if not isinstance(test_data, dict):
                continue
            total_tests += 1
            status = test_data.get("status")
            reason = test_data.get("reason") or ""
            is_failed = False

            if isinstance(status, str):
                if status.lower() in ("failure", "failed"):
                    is_failed = True
            elif isinstance(status, dict):
                if "Failure" in status or "failed" in status:
                    is_failed = True
                    if not reason and isinstance(status.get("Failure"), str):
                        reason = status["Failure"]

            if is_failed:
                reason_lc = str(reason).lower()
                if "setup failed" in reason_lc or "revert: setup" in reason_lc:
                    setup_errors.append(f"{test_name}: {reason}")
                else:
                    failed_tests.append((test_name, test_data))

    if setup_errors:
        return ValidationResult(
            outcome=Outcome.HARNESS_ERROR,
            backend=backend_name,
            property_id=property_id,
            error_message=f"Harness setUp reverted: {'; '.join(setup_errors)}",
            raw_artifact_path=raw_log_path,
        )

    if total_tests == 0 and returncode != 0:
        return ValidationResult(
            outcome=Outcome.HARNESS_ERROR,
            backend=backend_name,
            property_id=property_id,
            error_message="No tests executed and forge exited with error",
            raw_artifact_path=raw_log_path,
        )

    if failed_tests:
        failing_name, failing_data = failed_tests[0]
        counterexample = failing_data.get("counterexample") or {}
        decoded_logs = failing_data.get("decoded_logs") or []
        reason = failing_data.get("reason") or "Invariant violated in bundle differential test"

        witness = Witness(
            backend=backend_name,
            reproducible_test_code=harness_code,
            user_op_json=(
                counterexample
                if isinstance(counterexample, dict)
                else {"raw_counterexample": str(counterexample)}
            ),
            trace_events=(
                decoded_logs if isinstance(decoded_logs, list) else [str(decoded_logs)]
            ),
            is_valid=True,
        )

        # Map the failing test name to an obligation ID if possible
        obligation_id: Optional[str] = None
        match = re.search(r"test_obligation_([a-zA-Z0-9_\-]+)", failing_name)
        if match:
            obligation_id = match.group(1)
        else:
            obligation_id = failing_name

        return ValidationResult(
            outcome=Outcome.VIOLATED,
            backend=backend_name,
            property_id=property_id,
            failing_obligation_id=obligation_id,
            witness=witness,
            error_message=str(reason),
            raw_artifact_path=raw_log_path,
        )

    return ValidationResult(
        outcome=Outcome.HELD,
        backend=backend_name,
        property_id=property_id,
        raw_artifact_path=raw_log_path,
    )


# ---------------------------------------------------------------------------
# Backend class
# ---------------------------------------------------------------------------


class DifferentialSimBackend(ValidationBackend):
    """
    Bundle Differential Simulator Backend (Step F4).

    Builds a real ``n``-operation bundle through ``EntryPoint.handleOps`` and
    verifies that the invariant from ``property.required_condition`` holds after
    execution.  Violations (e.g. CouponPaymaster double-spend) are caught by
    counting ``UserOperationEvent(success=true)`` logs: if more than one op in
    the bundle is sponsored with the same coupon the invariant is violated.

    When ``forge`` is not installed the backend returns ``HARNESS_ERROR``
    immediately without raising.
    """

    BACKEND_NAME = "DifferentialSim"

    def __init__(
        self,
        forge_path: Optional[str] = None,
        test_dir: str = "contracts/test/generated",
        artifact_dir: str = "contracts/test/artifacts",
        bundle_size: int = 2,
        timeout: int = 60,
    ) -> None:
        self.test_dir = test_dir
        self.artifact_dir = artifact_dir
        self.bundle_size = bundle_size
        self.timeout = timeout
        os.makedirs(self.test_dir, exist_ok=True)
        os.makedirs(self.artifact_dir, exist_ok=True)
        self.forge_path: Optional[str] = forge_path if forge_path is not None else _find_forge()

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def validate(
        self,
        property: Property,
        binding: PropertyBinding,
        facts: ContractFacts,
    ) -> ValidationResult:
        """
        Build a bundle differential harness, run ``forge test --json``, and
        return a structured ValidationResult.

        Only processes SIM-type properties; all others return HELD immediately.
        """
        if property.template_type != PropertyType.SIM:
            return ValidationResult(
                outcome=Outcome.HELD,
                backend=self.BACKEND_NAME,
                property_id=property.property_id,
            )

        clean_id = re.sub(r"[^a-zA-Z0-9_]", "_", property.property_id)
        artifact_prop_dir = os.path.join(self.artifact_dir, clean_id)
        os.makedirs(artifact_prop_dir, exist_ok=True)
        raw_log_path = os.path.join(artifact_prop_dir, "bundle_run.log")

        # Graceful degradation: forge not installed → HARNESS_ERROR
        if not self.forge_path:
            return ValidationResult(
                outcome=Outcome.HARNESS_ERROR,
                backend=self.BACKEND_NAME,
                property_id=property.property_id,
                error_message=(
                    "'forge' binary not found on PATH. "
                    "Install Foundry: curl -L https://foundry.paradigm.xyz | bash && foundryup"
                ),
                raw_artifact_path=raw_log_path,
            )

        # Derive invariant comment from the bound property (not a hardcoded string)
        invariant_comment = (property.required_condition or "").replace("\n", " ").strip()
        contract_name = facts.contract_name
        harness_code = _generate_harness(
            contract_name=contract_name,
            clean_id=clean_id,
            invariant_comment=invariant_comment,
            bundle_size=self.bundle_size,
        )

        contract_test_name = f"Test_BundleDiff_{clean_id}"
        test_file_path = os.path.join(self.test_dir, f"{contract_test_name}.t.sol")

        with open(test_file_path, "w", encoding="utf-8") as f:
            f.write(harness_code)

        cmd = [
            self.forge_path,
            "test",
            "--match-contract", contract_test_name,
            "--json",
        ]

        try:
            result = subprocess.run(
                cmd,
                capture_output=True,
                encoding="utf-8",
                errors="replace",
                cwd=os.path.abspath("."),
                env=os.environ.copy(),
                timeout=self.timeout,
            )
            raw_output = (result.stdout or "") + "\n" + (result.stderr or "")
            with open(raw_log_path, "w", encoding="utf-8") as f:
                f.write(raw_output)

            json_data = _extract_json(result.stdout or "")
            if json_data is None:
                return ValidationResult(
                    outcome=Outcome.HARNESS_ERROR,
                    backend=self.BACKEND_NAME,
                    property_id=property.property_id,
                    error_message=(
                        f"Harness compilation or execution failed "
                        f"(exit code {result.returncode}) — no JSON output"
                    ),
                    raw_artifact_path=raw_log_path,
                )

            return _evaluate_json_results(
                json_data=json_data,
                returncode=result.returncode,
                harness_code=harness_code,
                property_id=property.property_id,
                raw_log_path=raw_log_path,
                backend_name=self.BACKEND_NAME,
            )

        except subprocess.TimeoutExpired:
            with open(raw_log_path, "w", encoding="utf-8") as f:
                f.write("TIMEOUT: forge test exceeded time limit\n")
            return ValidationResult(
                outcome=Outcome.TIMEOUT,
                backend=self.BACKEND_NAME,
                property_id=property.property_id,
                error_message=f"Execution timed out after {self.timeout}s",
                raw_artifact_path=raw_log_path,
            )
        except Exception as exc:
            with open(raw_log_path, "w", encoding="utf-8") as f:
                f.write(f"HARNESS_ERROR: {exc}\n")
            return ValidationResult(
                outcome=Outcome.HARNESS_ERROR,
                backend=self.BACKEND_NAME,
                property_id=property.property_id,
                error_message=f"Harness execution error: {exc}",
                raw_artifact_path=raw_log_path,
            )
