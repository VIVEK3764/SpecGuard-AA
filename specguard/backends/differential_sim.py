def _find_forge() -> Optional[str]:
    """Return the forge binary path, or None if Foundry is not installed."""
    return shutil.which("forge")


# ---------------------------------------------------------------------------
# Harness template
# ---------------------------------------------------------------------------

# Harness is parameterised on:
#   {contract_name}   – Solidity class name
#   {clean_id}        – sanitised property ID used for the test contract name
#   {bundle_size}     – integer (default 2)
#   {invariant_comment} – the required_condition text from the property (comment only)
#
# The invariant assertion is structural: we check that two operations using the
# same coupon / resource cannot *both* be sponsored.  Concretely the harness
# asserts that at most one operation in the bundle succeeds from the paymaster's
# perspective (i.e. postOp does not revert for more than one op).
#
# Because we cannot statically know the exact ABI of the target paymaster, the
# harness uses the standard ERC-4337 ``IEntryPoint.handleOps`` path and captures
# the ``UserOperationEvent`` log to count successful pays.  Failure of the second
# op's postOp is what constitutes a double-spend catch.
#
# Note: ``vm.expectRevert`` on ``handleOps`` is intentionally NOT used — ERC-4337
# does not revert the whole bundle on a single op failure.  Instead we count the
# emitted ``UserOperationEvent`` success flags.

_HARNESS_TEMPLATE = """\
// SPDX-License-Identifier: MIT
// AUTO-GENERATED by SpecGuard-AA DifferentialSimBackend (Step F4) — do not edit.
pragma solidity ^0.8.23;

import "forge-std/Test.sol";
import "@account-abstraction/contracts/core/EntryPoint.sol";
import "@account-abstraction/contracts/interfaces/PackedUserOperation.sol";
import "@account-abstraction/contracts/interfaces/IEntryPoint.sol";
import "../../src/worked_examples/{contract_name}.sol";

/// @title  Bundle Differential Simulation Test for {contract_name}
/// @notice Builds a {bundle_size}-operation bundle using the same resource and
///         drives it through EntryPoint.handleOps to detect invariant violations.
///
/// Invariant under test (from property.required_condition):
///   {invariant_comment}
///
/// The invariant holds iff at most ONE of the {bundle_size} operations in the
/// bundle is sponsored by the paymaster (i.e. the resource cannot be double-spent).
contract Test_BundleDiff_{clean_id} is Test {{

    EntryPoint  public entryPoint;
    {contract_name} public paymaster;

    address public beneficiary  = makeAddr("beneficiary");
    address public sender1      = makeAddr("sender1");
    address public sender2      = makeAddr("sender2");

    // ERC-4337 UserOperationEvent(bytes32 userOpHash, address sender,
    //   address paymaster, uint256 nonce, bool success, uint256 actualGasCost,
    //   uint256 actualGasUsed)
    event UserOperationEvent(
        bytes32 indexed userOpHash,
        address indexed sender,
        address indexed paymaster,
        uint256 nonce,
        bool    success,
        uint256 actualGasCost,
        uint256 actualGasUsed
    );

    function setUp() public {{
        entryPoint = new EntryPoint();
        // Paymaster constructor: (entryPoint, sponsor/owner)
        paymaster  = new {contract_name}(address(entryPoint), address(this));

        // Fund accounts so gas accounting doesn't revert
        vm.deal(address(paymaster), 100 ether);
        vm.deal(sender1, 10 ether);
        vm.deal(sender2, 10 ether);
        // Deposit paymaster stake into EntryPoint
        paymaster.deposit{{value: 10 ether}}();
    }}

    /// @dev Build an op for a given sender with minimal gas limits and
    ///      paymasterAndData pointing at our paymaster + a shared coupon hash.
    function _buildOp(
        address sender,
        uint256 nonce,
        bytes32 couponHash
    ) internal view returns (PackedUserOperation memory op) {{
        op.sender           = sender;
        op.nonce            = nonce;
        // accountGasLimits: high 128 bits = verificationGasLimit, low 128 bits = callGasLimit
        op.accountGasLimits = bytes32((uint256(500_000) << 128) | uint256(200_000));
        // gasFees: high 128 bits = maxPriorityFeePerGas, low 128 bits = maxFeePerGas
        op.gasFees          = bytes32((uint256(1 gwei) << 128) | uint256(2 gwei));
        // paymasterAndData: 20 bytes paymaster | 16 bytes verGasLimit | 16 bytes postOpGasLimit | coupon
        op.paymasterAndData = abi.encodePacked(
            address(paymaster),
            uint128(300_000),   // paymasterVerificationGasLimit
            uint128(100_000),   // paymasterPostOpGasLimit
            couponHash
        );
        // Blank signature — paymaster validates via couponHash, not sig
        op.signature = hex"";
    }}

    /// @notice Core bundle differential test.
    ///
    /// Flow:
    ///   1. simulateValidation(op1) — must not revert (resource not yet consumed).
    ///   2. simulateValidation(op2) — must not revert (resource not yet consumed).
    ///   3. handleOps([op1, op2])  — drives the full bundle.
    ///   4. Invariant: count UserOperationEvent(success=true) emitted by the
    ///      paymaster address.  VIOLATION if count >= {bundle_size} (both
    ///      operations were sponsored with the same coupon).
    function testBundle_invariantHolds() public {{
        bytes32 sharedCoupon = keccak256("shared-coupon-42");

        PackedUserOperation memory op1 = _buildOp(sender1, 0, sharedCoupon);
        PackedUserOperation memory op2 = _buildOp(sender2, 0, sharedCoupon);

        // Step 1 & 2: each op validates in isolation
        // simulateValidation reverts with ValidationResult — that is expected.
        // A revert with a *non* ValidationResult error would be a harness issue.
        try entryPoint.simulateValidation(op1) {{}} catch {{}}
        try entryPoint.simulateValidation(op2) {{}} catch {{}}

        // Step 3: submit the bundle
        PackedUserOperation[] memory bundle = new PackedUserOperation[]({bundle_size});
        bundle[0] = op1;
        bundle[1] = op2;

        // Record logs to count successes
        vm.recordLogs();
        try entryPoint.handleOps(bundle, payable(beneficiary)) {{}} catch {{}}
        Vm.Log[] memory logs = vm.getRecordedLogs();

        // Step 4: count sponsored (success=true) ops from the paymaster
        bytes32 eventSig = keccak256(
            "UserOperationEvent(bytes32,address,address,uint256,bool,uint256,uint256)"
        );
        uint256 successCount = 0;
        for (uint256 i = 0; i < logs.length; i++) {{
            if (logs[i].topics[0] != eventSig) continue;
            // topics[2] = paymaster (indexed)
            address emittedPaymaster = address(uint160(uint256(logs[i].topics[2])));
            if (emittedPaymaster != address(paymaster)) continue;
            // data = abi.encode(nonce, success, actualGasCost, actualGasUsed)
            (, bool success_, ,) = abi.decode(logs[i].data, (uint256, bool, uint256, uint256));
            if (success_) successCount++;
        }}

        // Invariant: at most ONE op may be sponsored with the same coupon.
        // If the paymaster is VULNERABLE, both ops succeed → successCount == {bundle_size} → VIOLATED.
        // If the paymaster is COMPLIANT, the second op reverts → successCount <= 1 → HELD.
        assertLt(
            successCount,
            {bundle_size},
            "VIOLATION: same coupon was accepted by {bundle_size} operations in one bundle"
        );
    }}
}}
"""


def _generate_harness(
    contract_name: str,
    clean_id: str,
    invariant_comment: str,
    bundle_size: int = 2,
) -> str:
    return _HARNESS_TEMPLATE.format(
        contract_name=contract_name,
        clean_id=clean_id,
        bundle_size=bundle_size,
        invariant_comment=invariant_comment,
    )


