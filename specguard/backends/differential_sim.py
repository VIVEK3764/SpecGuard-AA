"""
Bundle Differential Simulator Backend for SpecGuard-AA — Step F4.

The ERC-4337 EntryPoint validates *every* operation in a bundle **before**
executing any of them.  The classic double-spend attack (e.g. CouponPaymaster
replay) exploits the gap: each operation validates cleanly in isolation, but
the shared resource is exhausted during bundle execution so the second
postOp fails.

This backend models that attack directly by building a real multi-operation
bundle, confirming each operation validates in isolation, then driving the
whole bundle through ``EntryPoint.handleOps`` and asserting the invariant
derived from the bound property's ``required_condition`` field.

Design decisions
----------------
* Harness template: Solidity test that builds ``n`` UserOperations using the
  same resource (coupon / nonce / slot) and submits them as a bundle via
  ``handleOps``.  The invariant is parameterised from ``property.required_condition``
  so no hardcoded string from the Python side decides the outcome (Rule B).
* Outcome is determined by parsing ``forge test --json`` structured output —
  the same ``_extract_json`` / ``_evaluate_json_results`` pattern established
  in F2 (FoundryFuzz backend).
* ``n=2`` is the default bundle size (the plan says "n=2 suffices for the coupon
  case; parameterise").
* Forge / Foundry absent → ``HARNESS_ERROR`` (graceful degradation, same as F2/F3).
* Artifact logs written to ``contracts/test/artifacts/<clean_id>/bundle_run.log``.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
from typing import Any, Dict, List, Optional, Tuple

from specguard.backends.base import ValidationBackend
from specguard.models import (
    ContractFacts,
    Outcome,
    Property,
    PropertyBinding,
    PropertyType,
    Role,
    ValidationResult,
    Witness,
)


